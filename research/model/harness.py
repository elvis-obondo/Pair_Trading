UNIT = "pair"
VERSION = "v1"
VAULT_START = pd.Timestamp("2026-07-13T00:00:00Z")   # A4: vault = t0 >= this
GAP_DAY = pd.Timestamp("2026-07-12T00:00:00Z")        # A4: events with t0 on this UTC day are used nowhere
SEARCH_END = GAP_DAY                                   # A4: search period = t0 before 2026-07-12 00:00 UTC
N_STEPS = 20                                           # A2: twenty half-hour steps over 10 h
STEP_MINUTES = 30

# A4: expanding-window test blocks, 30 calendar days, starting 2025-11-21 00:00 UTC; the 8th is cut at the
# gap day. Written out explicitly (not generated by a loop) so the exact dates in the brief are checkable
# by eye against this list.
TEST_BLOCK_STARTS = [pd.Timestamp(d + "T00:00:00Z") for d in
                      ["2025-11-21", "2025-12-21", "2026-01-20", "2026-02-19",
                       "2026-03-21", "2026-04-20", "2026-05-20", "2026-06-19"]]
TEST_BLOCK_ENDS = TEST_BLOCK_STARTS[1:] + [GAP_DAY]
assert len(TEST_BLOCK_STARTS) == 8
assert (TEST_BLOCK_ENDS[-1] - TEST_BLOCK_STARTS[-1]).days == 23, "the 8th block must be 23 days, per the brief"
for i in range(7):
    assert (TEST_BLOCK_ENDS[i] - TEST_BLOCK_STARTS[i]).days == 30, f"block {i} must be 30 days"

EMBARGO = pd.Timedelta(days=1)


def assert_search_only(df, where):
    """Raises if any row of `df` has t0 >= SEARCH_END (the gap day or the vault). Factored out as a real
    function, not an inline `assert` statement, so B3 proof 5 can monkeypatch THIS specific check off (not
    Python's -O flag, which would disable every assert in the process) to demonstrate that it is this check
    -- not an accident of date-range filtering elsewhere -- that catches a vault-dated row reaching
    build_folds, build_hazard_rows or score_fold."""
    bad = df[df["t0"] >= SEARCH_END]
    if len(bad):
        raise AssertionError(f"{where}: {len(bad)} row(s) with t0 >= SEARCH_END (gap day or vault), "
                              f"max t0 = {df['t0'].max()}")


def _schema_columns(name):
    import pyarrow.parquet as pq
    return set(pq.read_schema(os.path.join(MF.WORK, UNIT, name)).names)


def load_search_events(columns=None):
    """Every pair-unit event with t0 < SEARCH_END (gap day excluded) AND label_gap == 0 (A5: the harness
    scores "usable events" only; a label_gap=1 event's reach_10h/chance_10h/minutes_to_mu are NaN by
    construction, so it cannot be scored or hazard-rowed). The vault is excluded here too, at load time,
    with a safety assert. Returns a DataFrame indexed by event_id with `t0` (entry_time + 30 min)."""
    need = set(columns or []) | {"event_id", "label_gap", "reach_10h", "chance_10h", "minutes_to_mu"}
    events_cols = {c for c in need if c in _schema_columns("events.parquet")} | {"event_id", "entry_time"}
    ev = MF.open_version(VERSION, UNIT, "events.parquet", columns=sorted(events_cols))
    labels_cols = {c for c in need if c in _schema_columns("labels.parquet")} | \
        {"event_id", "label_gap", "reach_10h", "chance_10h", "minutes_to_mu"}
    lb = MF.open_version(VERSION, UNIT, "labels.parquet", columns=sorted(labels_cols))
    df = ev.merge(lb, on="event_id", how="inner", validate="one_to_one")
    df["t0"] = pd.to_datetime(df["entry_time"], utc=True) + pd.Timedelta(minutes=30)

    n_total = len(df)
    before_search_end = df["t0"] < SEARCH_END
    on_gap_day = (df["t0"] >= GAP_DAY) & (df["t0"] < GAP_DAY + pd.Timedelta(days=1))
    df = df[before_search_end & ~on_gap_day]
    n_after_date_filter = len(df)

    n_label_gap = int((df["label_gap"] != 0).sum())
    df = df[df["label_gap"] == 0].copy()
    print(f"[HARNESS] load_search_events: {n_total:,} merged rows -> {n_after_date_filter:,} after the "
          f"date/gap-day filter -> {len(df):,} after dropping {n_label_gap:,} label_gap=1 rows")

    assert df["t0"].max() < VAULT_START, "a vault-period row reached the search loader -- this must never happen"
    assert not ((df["t0"] >= GAP_DAY) & (df["t0"] < GAP_DAY + pd.Timedelta(days=1))).any(), "a gap-day row survived the filter"
    return df.set_index("event_id", drop=False)


def check_inputs(columns):
    """Raises unless every name in `columns` is IN per research/model/inputs_v1_pair.csv (the frozen input
    list). Model-fitting code MUST call this before fitting on any column set; B3 proof 1 exercises it.
    Logs the csv's sha256 so the check is tied to a specific frozen file, not whatever happens to be on
    disk."""
    import csv
    path = os.path.join(HERE, "inputs_v1_pair.csv")
    rows = list(csv.DictReader(open(path)))
    in_set = {r["column"] for r in rows if r["in_out"] == "IN"}
    bad = [c for c in columns if c not in in_set]
    print(f"[HARNESS] check_inputs: {len(columns)} columns checked against inputs_v1_pair.csv "
          f"(sha256 {MF.sha(path)}); {len(bad)} not IN")
    if bad:
        raise ValueError(f"columns not in the frozen IN list (inputs_v1_pair.csv): {bad}")
    return True


_ROW_ORDER_CHECKED = set()  # files already confirmed to have event_id == row position 0..N-1


def _assert_positional_row_order(file):
    """event_id is the literal row position (0..N-1) within a v1 pair group file (the same invariant the
    duplicate audit relied on and asserted -- checked here too, not assumed, since load_features's whole
    memory-saving design depends on it to index by position instead of joining on event_id)."""
    if file in _ROW_ORDER_CHECKED:
        return
    import pyarrow.parquet as pq
    ids = pq.read_table(os.path.join(MF.WORK, UNIT, file), columns=["event_id"]).column(0).to_numpy()
    assert np.array_equal(ids, np.arange(len(ids))), \
        f"{file}: event_id is not the literal row position 0..N-1 -- load_features's positional indexing would be wrong"
    _ROW_ORDER_CHECKED.add(file)


def load_features(event_ids, columns):
    """Loads the given IN `columns` for exactly the given `event_ids`, as a single preallocated float32
    matrix, with no pandas merge/join (checker, 2026-10-27, round 2): event_id is the row's literal
    position in every v1 pair file (asserted in _assert_positional_row_order, once per file), so each
    column is read once, cast to float32, and written directly into its slice of the matrix by positional
    (not joined) indexing -- memory stays O(n_events x n_columns), never O(6,697,756 x n_columns) for a
    merged intermediate frame. The two string IN columns (ticker_a, ticker_b) are factorised to integer
    category codes here (not left as strings), since this loader's only consumer is numeric model fitting;
    no other preprocessing (imputation, scaling) is done -- that is model-fitting code's job, done on the
    fold's TRAIN rows only, per A4.

    Round 1's version resolved a column's file from ALL csv rows (IN and OUT), so a column dropped as a
    duplicate in one file but kept IN in another (beta, beta_stab: IN in events.parquet, OUT/duplicate_
    dropped in g2.parquet) could silently resolve to the WRONG, dropped copy -- fixed by building
    file_for_col from IN rows only, and asserting every (file, column) actually loaded is an IN row.

    Returns (X, columns) where X is a (len(event_ids), len(columns)) float32 ndarray in that column order."""
    check_inputs(columns)
    import csv
    rows = list(csv.DictReader(open(os.path.join(HERE, "inputs_v1_pair.csv"))))
    in_files_for_col = {}
    for r in rows:
        if r["in_out"] == "IN":
            in_files_for_col.setdefault(r["column"], []).append(r["file"])
    ambiguous = {c: in_files_for_col[c] for c in columns if len(in_files_for_col.get(c, [])) > 1}
    assert not ambiguous, f"columns with more than one IN file (ambiguous): {ambiguous}"
    missing = [c for c in columns if c not in in_files_for_col]
    assert not missing, f"columns not IN anywhere (should have been caught by check_inputs): {missing}"
    file_for_col = {c: in_files_for_col[c][0] for c in columns}
    in_pairs = {(r["file"], r["column"]) for r in rows if r["in_out"] == "IN"}
    for c in columns:
        assert (file_for_col[c], c) in in_pairs, \
            f"{file_for_col[c]}/{c} resolved but is not an IN row -- refusing to load it"

    event_ids = np.asarray(event_ids)
    n = len(event_ids)
    assert np.all((event_ids >= 0) & (event_ids < 6_697_756)), "an event_id is outside the v1 pair row range"
    X = np.empty((n, len(columns)), dtype=np.float32)

    import pyarrow as pa
    import pyarrow.compute as pc
    import pyarrow.parquet as pq
    by_file = {}
    for j, c in enumerate(columns):
        by_file.setdefault(file_for_col[c], []).append((j, c))
    for f, items in by_file.items():
        _assert_positional_row_order(f)
        MF.verify(VERSION, [f"{UNIT}/{f}"])
        for j, c in items:
            arr = pq.read_table(os.path.join(MF.WORK, UNIT, f), columns=[c]).column(0)
            sliced = arr.take(pa.array(event_ids))   # select rows BY POSITION first, never materialise the full column as a copy
            if pa.types.is_string(arr.type) or pa.types.is_large_string(arr.type):
                import pandas as pd_
                codes, _ = pd_.factorize(sliced.to_pandas().to_numpy())
                X[:, j] = codes.astype(np.float32)
            else:
                X[:, j] = pc.cast(sliced, pa.float32()).to_numpy(zero_copy_only=False)
    return X, columns


def build_folds(events):
    """A4: one dict per fold k (0..7): test (start, end), train/val/test event_id arrays, plus the embargo
    drop counts and fit-day bookkeeping the fold report (report_fold) and B2's own stated requirements need.
    Entry assert: every event in `events` has t0 < SEARCH_END (a safety check, not a restatement of the
    loader's filter -- this is what a mis-dated row injected AFTER loading must trip)."""
    assert_search_only(events, "build_folds")
    day = events["t0"].dt.floor("D")
    folds = []
    for k, (test_start, test_end) in enumerate(zip(TEST_BLOCK_STARTS, TEST_BLOCK_ENDS)):
        fit_cutoff = test_start - EMBARGO                      # embargo before the test block
        fit_mask = events["t0"] < fit_cutoff
        n_before_test_embargo = int(((events["t0"] >= fit_cutoff) & (events["t0"] < test_start)).sum())
        fit_days = sorted(day[fit_mask].unique())
        if not fit_days:
            folds.append({"k": k, "test_start": test_start, "test_end": test_end, "fit_days": [],
                          "n_val_days": 0, "n_dropped_before_test_embargo": n_before_test_embargo,
                          "n_dropped_before_val_embargo": 0,
                          "train_ids": np.array([]), "val_ids": np.array([]), "test_ids": np.array([])})
            continue
        n_val_days = max(1, int(np.ceil(0.2 * len(fit_days))))   # A4: ceil(0.2 x distinct UTC days before the fit cutoff)
        val_days = set(fit_days[-n_val_days:])
        val_start_day = min(val_days)
        embargo_before_val_day = val_start_day - pd.Timedelta(days=1)

        train_mask = fit_mask & (day < embargo_before_val_day)
        val_mask = fit_mask & day.isin(val_days)
        test_mask = (events["t0"] >= test_start) & (events["t0"] < test_end)
        n_dropped_before_val_embargo = int((fit_mask & (day == embargo_before_val_day)).sum())

        train_ids = events.index[train_mask].to_numpy()
        val_ids = events.index[val_mask].to_numpy()
        test_ids = events.index[test_mask].to_numpy()

        assert len(set(train_ids) & set(val_ids)) == 0
        assert len(set(train_ids) & set(test_ids)) == 0
        assert len(set(val_ids) & set(test_ids)) == 0
        for name, ids in (("train", train_ids), ("val", val_ids), ("test", test_ids)):
            if len(ids):
                assert (events.loc[ids, "t0"] < SEARCH_END).all(), f"fold {k} {name} set contains t0 >= SEARCH_END"
        assert events.loc[train_ids, "t0"].max() < embargo_before_val_day if len(train_ids) else True
        assert events.loc[val_ids, "t0"].min() >= val_start_day if len(val_ids) else True
        assert events.loc[test_ids, "t0"].min() >= test_start if len(test_ids) else True
        assert events.loc[test_ids, "t0"].max() < test_end if len(test_ids) else True

        folds.append({"k": k, "test_start": test_start, "test_end": test_end, "fit_days": fit_days,
                      "n_val_days": n_val_days, "n_dropped_before_test_embargo": n_before_test_embargo,
                      "n_dropped_before_val_embargo": n_dropped_before_val_embargo,
                      "train_ids": train_ids, "val_ids": val_ids, "test_ids": test_ids})
    return folds


def report_fold(fold, events):
    """B2: 'prints each fold's date ranges, event counts, embargo drops and reach rate.'"""
    k = fold["k"]
    print(f"[FOLD {k}] test [{fold['test_start'].date()}, {fold['test_end'].date()})  "
          f"embargo drops: {fold['n_dropped_before_test_embargo']:,} before test, "
          f"{fold['n_dropped_before_val_embargo']:,} before validation")
    for name, ids in (("train", fold["train_ids"]), ("val", fold["val_ids"]), ("test", fold["test_ids"])):
        if len(ids):
            sub = events.loc[ids]
            print(f"   {name}: n={len(ids):,} dates=[{sub['t0'].min().date()}, {sub['t0'].max().date()}] "
                  f"reach_10h_rate={float(sub['reach_10h'].mean()):.4f}")
        else:
            print(f"   {name}: n=0")


def split_hazard_by_fold(fold, hazard):
    """B2: 'keyed by event_id, so all rows of one event fall in one fold and one side of every boundary
    (asserted).' Splits the hazard frame by event_id membership in the fold's train/val/test sets and
    asserts every event selected has ALL of its rows selected -- none split across a boundary."""
    train_ids, val_ids, test_ids = set(fold["train_ids"]), set(fold["val_ids"]), set(fold["test_ids"])
    is_train = hazard["event_id"].isin(train_ids)
    is_val = hazard["event_id"].isin(val_ids)
    is_test = hazard["event_id"].isin(test_ids)
    assert not (is_train & is_val).any(), f"fold {fold['k']}: a hazard row is in both train and val"
    assert not (is_train & is_test).any(), f"fold {fold['k']}: a hazard row is in both train and test"
    assert not (is_val & is_test).any(), f"fold {fold['k']}: a hazard row is in both val and test"
    full_counts = hazard.groupby("event_id").size()
    out = {}
    for name, mask in (("train", is_train), ("val", is_val), ("test", is_test)):
        sub = hazard[mask]
        sub_counts = sub.groupby("event_id").size()
        expected = full_counts.reindex(sub_counts.index)
        mismatched = sub_counts[sub_counts != expected]
        assert len(mismatched) == 0, f"fold {fold['k']} {name}: {len(mismatched)} events have rows split across a fold boundary"
        out[name] = sub
    return out["train"], out["val"], out["test"]


def drop_degenerate_for_fold(train_df, columns):
    """B1 brief: 'Columns degenerate only inside some folds stay IN; the harness drops them for that fold's
    fit and logs the count.' Checked on the fold's TRAIN rows only (the fit data), not val/test."""
    dropped = []
    for c in columns:
        x = train_df[c]
        if pd.api.types.is_numeric_dtype(x) or pd.api.types.is_bool_dtype(x):
            finite = x.notna()
            degenerate = finite.sum() == 0 or x[finite].nunique() <= 1
        else:
            nonnull = x.dropna()
            degenerate = len(nonnull) == 0 or nonnull.nunique() <= 1
        if degenerate:
            dropped.append(c)
    kept = [c for c in columns if c not in dropped]
    print(f"[HARNESS] fold train-set degenerate columns dropped: {len(dropped)} of {len(columns)}"
          + (f" ({dropped})" if dropped else ""))
    return kept, dropped


def build_hazard_rows(events):
    """A2: one row per step the event was still waiting, label 1 at the step minutes_to_mu falls in (step k
    covers minutes 30(k-1)+1 .. 30k), else 0; a non-reacher gives all N_STEPS=20 zero rows. Fully vectorised
    (np.repeat, no per-event Python loop): at ~6.7M events x up to 20 rows, a Python loop building one
    DataFrame per event would take hours and far too much memory (checker, 2026-10-27).
    Asserts, not clips: reach_10h must agree with isfinite(minutes_to_mu), and a reacher's minutes_to_mu
    must be an integer in [1, 600] -- a value outside that range is a data bug to catch, not silently clip
    away."""
    assert_search_only(events, "build_hazard_rows")
    assert (events["label_gap"] == 0).all(), "a label_gap=1 event reached build_hazard_rows"
    mtm = events["minutes_to_mu"].to_numpy(dtype=float)
    reach = events["reach_10h"].to_numpy(dtype=float)
    reached = np.isfinite(mtm)
    assert np.array_equal(reached, reach.astype(bool)), "reach_10h disagrees with isfinite(minutes_to_mu)"
    finite_mtm = mtm[reached]
    if finite_mtm.size:
        assert np.all(finite_mtm >= 1) and np.all(finite_mtm <= 600), "a reacher's minutes_to_mu is outside [1, 600]"
        assert np.all(finite_mtm == np.round(finite_mtm)), "minutes_to_mu is not integer-valued for a reacher"

    step_reach = np.ceil(mtm / STEP_MINUTES)         # NaN for non-reachers, 1..20 for reachers (asserted above)
    n_rows = np.where(reached, step_reach, N_STEPS).astype(np.int64)
    if reached.any():
        assert np.all(n_rows[reached] >= 1) and np.all(n_rows[reached] <= N_STEPS)

    event_ids = events.index.to_numpy()
    total = int(n_rows.sum())
    offsets = np.concatenate([[0], np.cumsum(n_rows)[:-1]])
    row_event = np.repeat(event_ids, n_rows)
    row_within = np.arange(total) - np.repeat(offsets, n_rows)
    steps = row_within + 1
    is_last_row = steps == np.repeat(n_rows, n_rows)
    labels = (is_last_row & np.repeat(reached, n_rows)).astype(np.int8)
    return pd.DataFrame({"event_id": row_event, "step": steps, "label": labels})


def gap(reach_10h, chance_10h):
    return float(np.mean(reach_10h) - np.mean(chance_10h))


def lift(top_reach, top_chance, all_reach, all_chance):
    return gap(top_reach, top_chance) - gap(all_reach, all_chance)


def score_fold(scores, events_test, rng):
    """A5 per-block scoring: rank by `scores` (model's P(reach within 10h)), top 10% by count, gap/lift
    against the whole block. Ties in `scores` are broken by a SEEDED RANDOM key, not row order (checker,
    2026-10-27: row order is event_id order, which is time order, so an untied argsort(-scores) would put a
    tied model's earliest events in the top 10% every time -- not neutral). `rng` must be a seeded
    np.random.Generator, logged by the caller; this function does not seed its own RNG."""
    assert_search_only(events_test, "score_fold")
    n = len(scores)
    n_top = max(1, int(np.ceil(0.10 * n)))
    tie_key = rng.random(n)
    order = np.lexsort((tie_key, -np.asarray(scores)))   # primary: scores descending; ties: tie_key ascending
    top_mask = np.zeros(n, dtype=bool)
    top_mask[order[:n_top]] = True
    reach = events_test["reach_10h"].to_numpy()
    chance = events_test["chance_10h"].to_numpy()
    return lift(reach[top_mask], chance[top_mask], reach, chance), top_mask


def day_block_bootstrap(day_of_event, values_top_mask, reach_10h, chance_10h, n_resamples, level, rng):
    """A5: bootstrap by whole UTC day of the EVENT's t0 (not of the test block), since one coin move can put
    many pair events of that coin on the same day and they must resample together. Returns (point_lift, lo,
    hi) at the given two-sided level. `rng` must be a seeded np.random.Generator (deterministic, logged by
    the caller) -- this function does not seed its own RNG.

    Aggregated by day FIRST (checker, 2026-10-27): concatenating a resample's row indices from scratch, for
    every one of n_resamples draws, over a population of millions of rows (the real scoring build) is slow.
    Resampling a day with multiplicity m is equivalent to counting it m times in every per-day sum (the mean
    over the resampled set only depends on those sums), so this precomputes six per-day sums ONCE (n, sum
    reach, sum chance, each for all rows and for the top-10% rows), then every resample is a multinomial
    draw over ~230 days and a weighted dot product -- identical numbers to the row-concatenation version,
    verified against it directly before this was adopted."""
    days, day_code = np.unique(day_of_event, return_inverse=True)
    n_days = len(days)
    top_code = day_code[values_top_mask]
    n_all = np.bincount(day_code, minlength=n_days).astype(np.float64)
    s_reach_all = np.bincount(day_code, weights=reach_10h, minlength=n_days)
    s_chance_all = np.bincount(day_code, weights=chance_10h, minlength=n_days)
    n_top = np.bincount(top_code, minlength=n_days).astype(np.float64)
    s_reach_top = np.bincount(top_code, weights=reach_10h[values_top_mask], minlength=n_days)
    s_chance_top = np.bincount(top_code, weights=chance_10h[values_top_mask], minlength=n_days)

    lifts = np.empty(n_resamples)
    for b in range(n_resamples):
        w = rng.multinomial(n_days, np.full(n_days, 1.0 / n_days))
        wn_all, wn_top = float(w @ n_all), float(w @ n_top)
        gap_all = (w @ s_reach_all) / wn_all - (w @ s_chance_all) / wn_all
        gap_top = (w @ s_reach_top) / wn_top - (w @ s_chance_top) / wn_top
        lifts[b] = gap_top - gap_all
    alpha = 1 - level
    lo, hi = np.quantile(lifts, [alpha / 2, 1 - alpha / 2])
    point = lift(reach_10h[values_top_mask], chance_10h[values_top_mask], reach_10h, chance_10h)
    return point, float(lo), float(hi)


def pooled_lift(reach_all, chance_all, top_mask_all):
    """A5: pooled lift over the CONCATENATED out-of-sample top-10% sets and block populations of all 8
    folds (each block's top 10% weighted by its size -- i.e. simple concatenation, not a mean of per-fold
    lifts, which would weight small and large blocks equally)."""
    return lift(reach_all[top_mask_all], chance_all[top_mask_all], reach_all, chance_all)


def pass_search(pooled_lift_value, ci_lo, per_fold_lift_positive_count, n_folds=8):
    """A5 PASS (search): pooled lift >= 0.05 AND interval lower end > 0 AND lift > 0 in >= 6 of 8 folds.
    Returns (verdict, reason) where verdict in {"PASS", "FAIL", "REGIME_DEPENDENT"}.
    Verdict order (planner ruling, 2026-10-27, settling the question raised in B2's first review): FAIL if
    the pooled lift is below 0.05 OR the 98.75% interval's lower end is <= 0, REGARDLESS of the fold count.
    REGIME_DEPENDENT only when BOTH of those clear and fewer than 6 of 8 folds have lift > 0. PASS only when
    all three hold. The lift and interval checks come first, not the fold-count check."""
    if pooled_lift_value < 0.05:
        return "FAIL", f"pooled lift {pooled_lift_value:.4f} < 0.05"
    if ci_lo <= 0:
        return "FAIL", f"98.75% interval lower end {ci_lo:.4f} <= 0"
    if per_fold_lift_positive_count < 6:
        return "REGIME_DEPENDENT", (f"lift {pooled_lift_value:.4f} and interval lower end {ci_lo:.4f} both "
                                     f"clear, but lift > 0 in only {per_fold_lift_positive_count} of {n_folds} "
                                     f"folds (need >= 6)")
    return "PASS", f"pooled lift {pooled_lift_value:.4f} >= 0.05, interval lower end {ci_lo:.4f} > 0, " \
                   f"{per_fold_lift_positive_count}/{n_folds} folds positive"
