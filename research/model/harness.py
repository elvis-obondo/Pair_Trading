"""HL-MODEL1 B2: the walk-forward harness for the pair unit, v1. One module, no model-specific logic.

Loads only through master_manifest.open_version("v1", "pair", ...) (verifies sha256 first). Builds the
8 expanding-window folds (A4), the hazard rows (A2), and the scoring (A5: lift, day-block bootstrap, the
6-of-8 fold rule). No permutation null and no seed checks anywhere (user, 2026-10-27: "i dont want any seed
checks"). Deterministic: every randomised step (bootstrap resampling, the score tie-break) takes a seeded
np.random.Generator passed IN by the caller, never seeded inside this module -- the seed is logged by the
caller, not here.

VAULT SAFETY: this module never loads an event with t0 >= VAULT_START. load_search_events() filters at load
time and asserts the result's max t0 is before VAULT_START. build_folds, build_hazard_rows and score_fold
each assert their OWN input's t0 < SEARCH_END at entry (checker, 2026-10-27: "the date masks just happen to
exclude a late row" is not the same as an assert that the run fails on one -- these are separate, explicit
checks, not a restatement of the loader's own filter). The vault itself is loaded only by
research/model/vault_loader.py, a separate file not imported here.
"""
