"""Writes the COSTS1 one-leg section (markdown) from logs/costs1/costs_legs.json (written by costs_legs.py; log diagnostics/costs_legs.log).
Every number is read from the json; sentences are templates filled from the data. Nothing is typed by hand.
    python research/model/diagnostics/costs_legs_section.py
"""
import hashlib
import json
import os

MODEL = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
C1 = os.path.join(MODEL, "logs", "costs1") + os.sep
J = json.load(open(C1 + "costs_legs.json"))
SRC = hashlib.sha256(open(C1 + "costs_legs.json", "rb").read()).hexdigest()[:12]
RUNS = [f"{s} open{mo} {fee}" for s in ("vault", "test") for mo in (10, 20) for fee in ("maker", "taker")]
TIERS = ["least liquid third", "middle third", "most liquid third"]
HEAD = "mover vs hedge (beta-adjusted, HEADLINE)"
SPL = ["long vs short", HEAD, "mover vs hedge (raw)", "larger vs smaller leg"]
L = []


def p(x, d=1):
    return "n/a" if x is None else f"{100 * x:.{d}f}%"


def usd(x):
    return f"${x:,.2f}"


def add(s=""):
    L.append(s)


def share(x, group_gross, run_gross):
    """a share whose denominator (the trade gross of its group) is zero, negative or under 5% of the run's gross is not meaningful"""
    return "n/m" if (x is None or group_gross <= 0 or group_gross < 0.05 * abs(run_gross)) else p(x)


def groups_of(run):
    seen = []
    for r in J[run]["splits"]:
        if r["group"] not in seen and not r["group"].startswith("ALL (opp"):
            seen.append(r["group"])
    return seen


add("# COSTS1 - one-leg check: is the profit mostly generated by one leg?")
add(f"Source: logs/costs1/costs_legs.json (sha256 {SRC}), written by diagnostics/costs_legs.py; the log is diagnostics/costs_legs.log. Rules: costs1_rules.md section 11. This section is written by diagnostics/costs_legs_section.py; no number is typed by hand.")
add()
add("## What is measured")
add("Gross profit of each leg of every saved trade (q 1% / no stop; the eight headline runs), from the prices between the entry and the exit: leg gross = leg dollars x direction x (price change). The two legs add up to the saved gross of the trade (receipts below). 'Close' uses the cleaned 1-minute closes the engine used. 'Mid' uses the exchange mid with the order-book table mid as the labelled fallback, on the trades with all four mids (same rules as the no-bounce section). Share = leg group's gross / the trade gross of the same set of trades.")
add("The mover is the leg whose 60-minute move before entry moved the spread more. Headline definition is beta-adjusted (|r60 of A| against |beta| x |r60 of B|); the raw version (larger |r60|) is printed beside it. Larger vs smaller leg is the same split as |beta| < 1 vs |beta| > 1.")
add()
add("## Receipts")
add("| run | trades | max abs diff, legs vs saved gross ($) | max relative deviation, saved fee vs rate x USD | trades with all four mids | mid legs total | section 10 mid gross | same-direction pairs (beta < 0) |")
add("|---|---|---|---|---|---|---|---|")
for r in RUNS:
    j = J[r]
    add(f"| {r} | {j['n']:,} | {j['max_err']:.1e} | {j['fee_rate_dev']:.1e} | {j['n_mid']:,} | {usd(j['mid_check']['mid_total'])} | {usd(j['mid_check']['section10'])} | {p(j['share_samedir'])} |")
add()
add("Coverage of trades with all four mids (ctxs + G8 fallback), by entry month and by tier (vault months, then test months):")
for per in ("vault", "test"):
    rr = [r for r in RUNS if r.startswith(per)]
    ms = sorted({m_ for r in rr for m_ in J[r]["cover_month"]})
    add("| run | " + " | ".join(ms) + " | " + " | ".join(TIERS) + " |")
    add("|---|" + "---|" * (len(ms) + 3))
    for r in rr:
        add(f"| {r} | " + " | ".join(p(J[r]["cover_month"].get(m_)) if m_ in J[r]["cover_month"] else "n/a" for m_ in ms) + " | " + " | ".join(p(J[r]["cover_tier"][t]) for t in TIERS) + " |")
    add()
for ver in ("close", "mid"):
    for sp in SPL:
        add(f"## Split: {sp} ({ver} prices)")
        add("Total gross of each leg group over all its legs, and its share of the trade gross of the same set (n/m = not meaningful: the group's trade gross is zero or negative or under 5% of the run's gross; the dollars are kept). Groups: all trades, the trade's least liquid tier, and each exit reason found.")
        n1, n2 = (("long", "short") if sp == "long vs short" else (("mover", "hedge") if "mover" in sp else ("larger", "smaller")))
        add(f"| run | group | trades | trade gross | {n1} total | {n1} mean per leg | {n1} share | {n2} total | {n2} mean per leg | {n2} share |")
        add("|---|---|---|---|---|---|---|---|---|---|")
        for r in RUNS:
            for row in J[r]["splits"]:
                if row["version"] != ver or row["split"] != sp or row["group"].startswith("ALL (opp"):
                    continue
                rg = J[r]["gross"] if ver == "close" else J[r]["mid_check"]["mid_total"]
                add(f"| {r} | {row['group']} | {row['n_trades']:,} | {usd(row['trade_gross'])} | {usd(row['a_total'])} | {usd(row['a_mean']) if row['a_mean'] is not None else 'n/a'} | {share(row['a_share'], row['trade_gross'], rg)} | {usd(row['b_total'])} | {usd(row['b_mean']) if row['b_mean'] is not None else 'n/a'} | {share(row['b_share'], row['trade_gross'], rg)} |")
        add()
    add(f"### Long vs short on opposite-direction pairs only ({ver} prices)")
    add("| run | trades | trade gross | long total | long share | short total | short share |")
    add("|---|---|---|---|---|---|---|")
    for r in RUNS:
        for row in J[r]["splits"]:
            if row["version"] == ver and row["group"].startswith("ALL (opp"):
                rg = J[r]["gross"] if ver == "close" else J[r]["mid_check"]["mid_total"]
                add(f"| {r} | {row['n_trades']:,} | {usd(row['trade_gross'])} | {usd(row['a_total'])} | {share(row['a_share'], row['trade_gross'], rg)} | {usd(row['b_total'])} | {share(row['b_share'], row['trade_gross'], rg)} |")
    add()
add("## One-leg trades")
add("Among trades with gross > 0: how many have one leg above 100% of the trade gross (the other leg strictly negative), how many have one leg carrying all of it with the other flat, the share of the run's positive gross those trades carry, and which leg it was. Among trades with gross < 0: the share where one leg made money.")
add("| run | prices | group | gross > 0 trades | one leg > 100% | share | share of positive gross | one leg, other flat | long / short leg (add up to the total only for opposite-direction pairs) | same-direction pairs among them | beta-adj. mover / hedge leg | larger / smaller leg | gross < 0 trades | one leg made money |")
add("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|")
for r in RUNS:
    for ver in ("close", "mid"):
        for g in ["ALL"] + TIERS:
            k = f"{ver}|{g}"
            if k not in J[r]["one_leg"]:
                continue
            o = J[r]["one_leg"][k]
            w = o["which"]
            add(f"| {r} | {ver} | {g} | {o['n_pos']:,} | {o['one_leg_pos']:,} | {p(o['share_pos'])} | {p(o['share_of_pos_gross'])} | {o['one_leg_other_flat']:,} | {w['long leg']:,} / {w['short leg']:,} | {w['same-direction pairs among them (long/short counts add up to the total only for opposite-direction pairs)']:,} | {w['beta-adj. mover leg']:,} / {w['beta-adj. hedge leg']:,} | {w['larger leg']:,} / {w['smaller leg']:,} | {o['n_neg']:,} | {o['one_leg_neg']:,} ({p(o['share_neg'])}) |")
add()
add("## Leg signs")
add("Up = leg gross > 0, down = < 0, flat = exactly 0. Trades and total gross per pair of leg signs, close prices and mid prices.")
add("| run | prices | " + " | ".join(k for k in J[RUNS[0]]["signs"]["close"]) + " |")
add("|---|---|" + "---|" * len(J[RUNS[0]]["signs"]["close"]))
for r in RUNS:
    for ver in ("close", "mid"):
        sg = J[r]["signs"][ver]
        add(f"| {r} | {ver} | " + " | ".join(f"{v['n']:,} trades, {usd(v['gross'])}" for v in sg.values()) + " |")
add()
add("## Market exposure")
add("Net notional = long dollars minus short dollars at entry (share of the trade's notional). BTC return over the trade from the 30-minute BTC file (price up to 30 minutes old at both ends; the primary reads the file's date as the bar's open, the alternative as its end). Slope and correlation are descriptive only (trades overlap in time). Exposure P&L = sum of net dollars x BTC return over each trade (assumes both legs move one-for-one with BTC).")
add("| run | mean net notional | mean net share | mean abs net share | BTC slope, $ gross per +1% BTC | correlation | slope, bp of notional per +1% | correlation (bp) | exposure P&L | gross (same trades) | alternative convention: slope / correlation |")
add("|---|---|---|---|---|---|---|---|---|---|---|")
for r in RUNS:
    e = J[r]["exposure"]
    b, a = e["btc"], e["btc_alt"]
    add(f"| {r} | {usd(e['net_mean'])} | {p(e['share_mean'])} | {p(e['abs_share_mean'])} | {b['slope']:+.3f} | {b['corr']:+.4f} | {b['slope_bp']:+.3f} | {b['corr_bp']:+.4f} | {usd(b['exposure_pnl'])} | {usd(b['gross'])} | {a['slope']:+.3f} / {a['corr']:+.4f} |")
add()
add("Mean gross per trade by tercile of the signed BTC return over the trade (primary convention), with the mean holding time and the share of mu exits in each tercile. The terciles are confounded with holding time (mu exits are short and winning, timeouts are long); do not read this as calm-market profit.")
add("| run | BTC down third | BTC middle third | BTC up third |")
add("|---|---|---|---|")
for r in RUNS:
    t = J[r]["exposure"]["btc"]["terciles"]
    add(f"| {r} | " + " | ".join(f"{usd(t[k]['mean'])} (n {t[k]['n']:,}; mean holding {t[k]['hold']:.0f} min; mu exits {p(t[k]['mu_share'])})" for k in ("BTC down third", "BTC middle third", "BTC up third")) + " |")
_sh = [r for r in RUNS if J[r]["exposure"]["btc"]["terciles"]["BTC middle third"]["hold"] < min(J[r]["exposure"]["btc"]["terciles"]["BTC down third"]["hold"], J[r]["exposure"]["btc"]["terciles"]["BTC up third"]["hold"])]
_mu = [r for r in RUNS if J[r]["exposure"]["btc"]["terciles"]["BTC middle third"]["mu_share"] > max(J[r]["exposure"]["btc"]["terciles"]["BTC down third"]["mu_share"], J[r]["exposure"]["btc"]["terciles"]["BTC up third"]["mu_share"])]
add(f"What the table shows: in {len(_sh)} of 8 runs the middle tercile (BTC return near zero) has a shorter mean holding time than both outer terciles, and in {len(_mu)} of 8 it has the highest share of mu exits. Holding time is therefore part of why the middle tercile differs; this table does not separate it from BTC.")
add()
add("## Costs per leg (fees and half-spread only)")
add("LEG NET IS NOT THE COSTED NET C: no depth impact, no funding, no fill model. This answers which leg makes the profit only. Fees are the saved fees split by leg dollars. Taker runs also carry the order-book half-spread at the entry and exit minute (own minute only; trades without it are left out). Maker runs show fees only; the maker fill model is not split by leg.")
add("Left out = trades in the group that this split cannot classify (same-direction pairs for long vs short, unclassified for mover vs hedge, equal legs for larger vs smaller), so the legs add up.")
add("| run | group | split | trades in the table / left out | first group: legs, gross, fees, half-spread, net | second group: legs, gross, fees, half-spread, net |")
add("|---|---|---|---|---|---|")
for r in RUNS:
    for k, blk in J[r]["costs"].items():
        g, nm = k.split("|")
        (a, va), (b, vb) = list(blk["cells"].items())
        add(f"| {r} | {g} | {nm} | {blk['trades']:,} / {blk['excluded_trades']:,} | {a}: {va['legs']:,}, {usd(va['gross'])}, {usd(va['fees'])}, {usd(va['half_spread'])}, {usd(va['net'])} | {b}: {vb['legs']:,}, {usd(vb['gross'])}, {usd(vb['fees'])}, {usd(vb['half_spread'])}, {usd(vb['net'])} |")
add()
add("Receipt: sum of leg nets vs the saved net A on the same trades; the gap is the funding paid net added back less the half-spread (asserted equal).")
add("The saved net A in this table is on the trades in the cost table (taker runs: only trades with a half-spread row at all four stamps), so it can differ from the run's net A on other sets (for example the matched set of the no-bounce section).")
add("| run | trades in the table / all trades | leg nets | saved net A (same trades) | funding paid net | half-spread |")
add("|---|---|---|---|---|---|")
for r in RUNS:
    q = J[r]["receipt_legnet"]
    add(f"| {r} | {q['n']:,} / {q['n_all']:,} | {usd(q['leg_net'])} | {usd(q['saved_net'])} | {usd(q['funding'])} | {usd(q['half_spread'])} |")
add()
add("## Reading, run by run (sentences filled from the tables above; close prices unless said)")
for r in RUNS:
    j = J[r]
    by = {(x["version"], x["split"], x["group"]): x for x in j["splits"]}
    ls, mh, lg = by[("close", "long vs short", "ALL")], by[("close", HEAD, "ALL")], by[("close", "larger vs smaller leg", "ALL")]
    ol = j["one_leg"]["close|ALL"]
    b = j["exposure"]["btc"]
    add(f"- **{r}**: saved gross {usd(j['gross'])}. Long legs made {usd(ls['a_total'])} ({p(ls['a_share'])} of the gross), short legs {usd(ls['b_total'])} ({p(ls['b_share'])}). Mover legs made {usd(mh['a_total'])} ({p(mh['a_share'])}), hedge legs {usd(mh['b_total'])} ({p(mh['b_share'])}); {mh['unclassified_legs']:,} legs unclassified. Larger-notional legs made {usd(lg['a_total'])} ({p(lg['a_share'])}), smaller legs {usd(lg['b_total'])} ({p(lg['b_share'])}). Of {ol['n_pos']:,} winning trades, {ol['one_leg_pos']:,} ({p(ol['share_pos'])}) had one leg above 100% of the gross; they carry {p(ol['share_of_pos_gross'])} of the positive gross. Gross against the BTC return: slope {b['slope']:+.3f} dollars per +1% BTC, correlation {b['corr']:+.4f}; exposure P&L {usd(b['exposure_pnl'])}.")
add()
add("## Notes (what the numbers are and are not)")
add("- Findings are reported, not acted on. No pick, exit, hedge ratio or parameter was changed.")
add("- Exposure P&L negative means the net market exposure lost money on average over the trades. It assumes a beta of 1 to BTC for both legs and is not a hedge-quality result.")
add("- Leg gross is price movement only. Depth impact, funding and the maker fill model are not split by leg.")
add("- The mover split classifies by the 60 minutes before entry, from closes. A stale close in that window can misplace a leg; the classification is the same in the mid version.")
add("- The BTC return over a trade is read from 30-minute prices, up to 30 minutes old at both ends; this blurs the slope toward zero. Slope and correlation carry no significance statement.")
open(C1 + "costs_legs_section.md", "w").write("\n".join(L) + "\n")
print(f"[LEGS-SECTION] wrote logs/costs1/costs_legs_section.md ({len(L)} lines) from costs_legs.json sha256 {SRC}")
